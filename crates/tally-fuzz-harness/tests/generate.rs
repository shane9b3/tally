//! Regenerates `fuzz/seeds/` and `fuzz/dict/` from the test fixtures
//! already in the repository (nothing external):
//!
//! ```sh
//! cargo test -p tally-fuzz-harness --test generate -- --ignored
//! ```
//!
//! Seeds over `MAX_SEED_BYTES` are skipped (the zip bombs and entry floods
//! of the malicious corpus), so the fuzzers start from small inputs. The
//! `*_parts` seeds are the fixtures' zip packages in the
//! `name \0 content \0 …` form of `tally_fuzz_harness::build_package`; the
//! `open` seeds are fixtures prefixed with their extension's index in
//! `OPEN_EXTS`. The dictionaries hold the XML element and attribute names
//! (and part names) found in the fixtures.

#![allow(clippy::unwrap_used)] // tests may unwrap (docs/contributing.md)

mod common;

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use common::{files_in, fuzz_dir, repo_root};

const MAX_SEED_BYTES: usize = 64 * 1024;

fn fixtures(dir: &str, exts: &[&str]) -> Vec<PathBuf> {
    files_in(&repo_root().join("tests/fixtures").join(dir))
        .into_iter()
        .filter(|p| {
            p.extension()
                .and_then(|e| e.to_str())
                .is_some_and(|e| exts.contains(&e))
        })
        .filter(|p| std::fs::metadata(p).is_ok_and(|m| m.len() as usize <= MAX_SEED_BYTES))
        .collect()
}

fn file_name(p: &Path) -> String {
    p.file_name().unwrap().to_string_lossy().into_owned()
}

struct Out {
    root: PathBuf,
}

impl Out {
    fn write(&self, target: &str, name: &str, data: &[u8]) {
        assert!(tally_fuzz_harness::target(target).is_some(), "{target}");
        if data.len() > MAX_SEED_BYTES * 2 {
            return;
        }
        let dir = self.root.join("seeds").join(target);
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(dir.join(name), data).unwrap();
    }

    fn dict(&self, name: &str, tokens: &BTreeSet<Vec<u8>>) {
        let dir = self.root.join("dict");
        std::fs::create_dir_all(&dir).unwrap();
        let mut s = String::from(
            "# libFuzzer dictionary, generated by\n\
             # cargo test -p tally-fuzz-harness --test generate -- --ignored\n",
        );
        for t in tokens {
            s.push('"');
            for &b in t {
                match b {
                    b'"' => s.push_str("\\\""),
                    b'\\' => s.push_str("\\\\"),
                    0x20..=0x7e => s.push(char::from(b)),
                    _ => s.push_str(&format!("\\x{b:02X}")),
                }
            }
            s.push_str("\"\n");
        }
        std::fs::write(dir.join(name), s).unwrap();
    }
}

/// Element names (`<x:y`, `</x:y>`) and attribute names (`x:y="`) in `xml`.
fn xml_tokens(xml: &[u8], into: &mut BTreeSet<Vec<u8>>) {
    let name_char = |b: u8| b.is_ascii_alphanumeric() || matches!(b, b':' | b'_' | b'-' | b'.');
    let mut i = 0;
    while i < xml.len() {
        if xml[i] == b'<' {
            let start = i + 1 + usize::from(xml.get(i + 1) == Some(&b'/'));
            let mut j = start;
            while j < xml.len() && name_char(xml[j]) {
                j += 1;
            }
            if j > start && j - start <= 64 {
                let mut t = b"<".to_vec();
                t.extend_from_slice(&xml[start..j]);
                into.insert(t);
            }
            i = j.max(i + 1);
        } else if xml[i] == b'=' && xml.get(i + 1).is_some_and(|&q| q == b'"' || q == b'\'') {
            let mut j = i;
            while j > 0 && name_char(xml[j - 1]) {
                j -= 1;
            }
            if j < i && i - j <= 64 && (j == 0 || xml[j - 1].is_ascii_whitespace()) {
                let mut t = xml[j..i].to_vec();
                t.extend_from_slice(b"=\"");
                into.insert(t);
            }
            i += 1;
        } else {
            i += 1;
        }
    }
}

/// The part names and XML tokens of a package given as parts.
fn parts_tokens(parts: &[u8], into: &mut BTreeSet<Vec<u8>>) {
    let mut chunks = parts.split(|&b| b == 0);
    while let Some(name) = chunks.next() {
        into.insert(name.to_vec());
        if let Some(content) = chunks.next() {
            xml_tokens(content, into);
        }
    }
}

fn open_ext_index(ext: &str) -> u8 {
    let i = tally_fuzz_harness::OPEN_EXTS
        .iter()
        .position(|e| *e == ext)
        .unwrap();
    u8::try_from(i).unwrap()
}

#[test]
#[ignore = "rewrites fuzz/seeds and fuzz/dict; run by hand"]
fn regenerate_seeds_and_dictionaries() {
    let out = Out { root: fuzz_dir() };
    let _ = std::fs::remove_dir_all(out.root.join("seeds"));
    let _ = std::fs::remove_dir_all(out.root.join("dict"));

    // ODS / SXC packages (and the small malicious ones).
    let mut ods_dict = BTreeSet::new();
    let ods_files: Vec<PathBuf> = [
        fixtures("ods", &["ods"]),
        fixtures("ods/charts", &["ods"]),
        fixtures("sxc", &["sxc"]),
        fixtures("malicious", &["ods", "odt"]),
    ]
    .concat();
    for p in &ods_files {
        let bytes = std::fs::read(p).unwrap();
        out.write("ods", &file_name(p), &bytes);
        if let Some(parts) = tally_fuzz_harness::package_to_parts(&bytes) {
            parts_tokens(&parts, &mut ods_dict);
            out.write("ods_parts", &format!("{}.parts", file_name(p)), &parts);
        }
    }
    for p in fixtures("fods", &["fods"]) {
        let bytes = std::fs::read(&p).unwrap();
        xml_tokens(&bytes, &mut ods_dict);
        out.write("fods", &file_name(&p), &bytes);
    }
    out.dict("ods.dict", &ods_dict);

    // XLSX packages.
    let mut xlsx_dict = BTreeSet::new();
    let xlsx_files: Vec<PathBuf> = [
        fixtures("xlsx", &["xlsx"]),
        fixtures("xlsx/charts", &["xlsx"]),
        fixtures("xlsx/malicious", &["xlsx"]),
    ]
    .concat();
    for p in &xlsx_files {
        let bytes = std::fs::read(p).unwrap();
        out.write("xlsx", &file_name(p), &bytes);
        if let Some(parts) = tally_fuzz_harness::package_to_parts(&bytes) {
            parts_tokens(&parts, &mut xlsx_dict);
            out.write("xlsx_parts", &format!("{}.parts", file_name(p)), &parts);
        }
    }
    out.dict("xlsx.dict", &xlsx_dict);

    // Single-file formats.
    let mut xmlss_dict = BTreeSet::new();
    for (target, dir, exts) in [
        ("xls", "xls", &["xls"][..]),
        ("xmlss", "xmlss", &["xml"][..]),
        ("csv", "csv", &["csv", "tsv"][..]),
        ("csv", "pivot", &["csv"][..]),
        ("html", "html", &["html"][..]),
        ("dbf", "dbf", &["dbf"][..]),
        ("dif", "dif", &["dif"][..]),
        ("sylk", "sylk", &["slk"][..]),
    ] {
        for p in fixtures(dir, exts) {
            let bytes = std::fs::read(&p).unwrap();
            if target == "xmlss" {
                xml_tokens(&bytes, &mut xmlss_dict);
            }
            out.write(target, &file_name(&p), &bytes);
        }
    }
    out.dict("xmlss.dict", &xmlss_dict);

    // `open`: one or two fixtures per format, prefixed with the extension.
    for (dir, name, ext) in [
        ("ods", "aoo-style.ods", "ods"),
        ("ods", "libreoffice-style.ods", "ods"),
        ("xlsx", "excel365-basic.xlsx", "xlsx"),
        ("xlsx", "libreoffice-style.xlsx", "xlsx"),
        ("xls", "basic.xls", "xls"),
        ("fods", "basic.fods", "fods"),
        ("sxc", "ooo1.sxc", "sxc"),
        ("xmlss", "basic.xml", "xml"),
        ("csv", "invoices.csv", "csv"),
        ("csv", "tabs.tsv", "tsv"),
        ("html", "two-tables.html", "html"),
        ("dbf", "customers.dbf", "dbf"),
        ("dif", "basic.dif", "dif"),
        ("sylk", "excel.slk", "slk"),
    ] {
        let bytes = std::fs::read(repo_root().join("tests/fixtures").join(dir).join(name)).unwrap();
        let mut data = vec![open_ext_index(ext)];
        data.extend_from_slice(&bytes);
        out.write("open", name, &data);
    }

    // Formulas: the tokenizer fixtures (dialect byte + source), plus the
    // conversions of stored Excel, R1C1 and AOO native formulas.
    let mut formula_dict: BTreeSet<Vec<u8>> = tally_formula::DEFAULT_FUNCTIONS
        .iter()
        .map(|f| format!("{f}(").into_bytes())
        .collect();
    for tok in [
        "of:=",
        "[.A1]",
        "[.A1:.B2]",
        "[$Sheet1.A1]",
        "#REF!",
        "#N/A",
        "#DIV/0!",
        "TRUE()",
        "{1;2|3}",
        "Sheet1!",
        "'Data 2'!",
        "$A$1",
        "A:A",
        "1:1",
        "R1C1",
        "R[-1]C[2]",
        "~",
        "!",
        "&",
        "^",
        "%",
        "<>",
        ">=",
        "\"",
        ";",
        ",",
        "..",
    ] {
        formula_dict.insert(tok.as_bytes().to_vec());
    }
    let mut n = 0u8;
    for p in files_in(&repo_root().join("crates/tally-formula/tests/fixtures/tokens")) {
        let text = std::fs::read_to_string(&p).unwrap();
        let src = json_string_field(&text, "src");
        let dialect = json_string_field(&text, "dialect");
        let (Some(src), Some(dialect)) = (src, dialect) else {
            continue;
        };
        let sel: u8 = match dialect.as_str() {
            "open-formula" => 0,
            "calc-a1" => 1,
            "excel-a1" => 2,
            _ => continue,
        };
        let mut data = vec![sel | (n << 4)];
        data.extend_from_slice(src.as_bytes());
        out.write("formula", &file_name(&p).replace(".json", ".txt"), &data);
        n = (n + 1) % 3;
    }
    for (sel, name, src) in [
        (
            3u8,
            "excel-stored.txt",
            "SUM(A1:B2,Sheet1!C3)*IF(A1>0,1,-1)",
        ),
        (3, "excel-3d.txt", "SUM('Data 2'!A1:A9)&\"x\""),
        (4, "r1c1.txt", "=SUM(R1C1:R[2]C[-1])+RC"),
        (5, "native.txt", "SUM(A1:B2;'Data 2'.C3)"),
    ] {
        let mut data = vec![sel];
        data.extend_from_slice(src.as_bytes());
        out.write("formula", name, &data);
    }
    out.dict("formula.dict", &formula_dict);

    // Number format codes (even selector) and cell input (odd selector).
    let codes = [
        "General",
        "0",
        "0.00",
        "#,##0.00",
        "#,##0.00 [$€-407];[RED]-#,##0.00 [$€-407]",
        "0%",
        "0.00E+00",
        "# ?/?",
        "# ??/16",
        "@",
        "YYYY-MM-DD",
        "DD.MM.YYYY HH:MM:SS",
        "[HH]:MM:SS",
        "MM/DD/YY AM/PM",
        "NNNNMMMM D, YYYY",
        "[$-F800]DDDD, MMMM DD, YYYY",
        "[NatNum1][$-411]0",
        "[>100][GREEN]0;[<-100][RED]0;0",
        "\"Total: \"0.0;\"neg\";\"zero\";\"text \"@",
        "_(* #,##0_);_(* (#,##0);_(* \"-\"_);_(@_)",
        "0.0,,\"M\"",
        "[~buddhist]YYYY-MM-DD",
        "GE.MM.DD",
        "?? ???/???",
    ];
    for (i, c) in codes.iter().enumerate() {
        let mut data = vec![0u8];
        data.extend_from_slice(c.as_bytes());
        out.write("numfmt", &format!("code-{i:02}.txt"), &data);
    }
    let inputs = [
        "1234.5",
        "-1,234.50",
        "1.234,50",
        "12%",
        "1e10",
        "$1,000",
        "2026-11-13",
        "13.11.2026",
        "11/13/26",
        "13 Nov 2026",
        "12:34:56.789",
        "1:30 PM",
        "TRUE",
        "1 1/2",
        "(123)",
    ];
    for (i, s) in inputs.iter().enumerate() {
        let mut data = vec![1u8];
        data.extend_from_slice(s.as_bytes());
        out.write("numfmt", &format!("input-{i:02}.txt"), &data);
    }
    let numfmt_dict: BTreeSet<Vec<u8>> = [
        "General",
        "YYYY",
        "YY",
        "MMMM",
        "MMM",
        "MM",
        "M",
        "DDDD",
        "DD",
        "D",
        "HH",
        "H",
        "SS",
        "AM/PM",
        "A/P",
        "[HH]",
        "[MM]",
        "[SS]",
        "NN",
        "NNN",
        "NNNN",
        "QQ",
        "WW",
        "E+",
        "E-",
        "#",
        "0",
        "?",
        "/",
        ",",
        ".",
        "%",
        "@",
        "*",
        "_",
        "\\",
        "\"",
        ";",
        "[RED]",
        "[GREEN]",
        "[COLOR12]",
        "[>",
        "[<=",
        "[$-407]",
        "[$€-407]",
        "[$-F800]",
        "[~buddhist]",
        "[NatNum1]",
        "[DBNum1]",
        "GE",
        "EE",
        "R",
        "TRUE",
        "FALSE",
    ]
    .iter()
    .map(|t| t.as_bytes().to_vec())
    .collect();
    out.dict("numfmt.dict", &numfmt_dict);
}

/// The value of the top-level string field `"key": "…"` in a small JSON
/// file (the token fixtures), with the common escapes undone.
fn json_string_field(text: &str, key: &str) -> Option<String> {
    let at = text.find(&format!("\"{key}\""))?;
    let rest = &text[at + key.len() + 2..];
    let rest = rest[rest.find('"')? + 1..].chars();
    let mut out = String::new();
    let mut esc = false;
    let mut chars = rest;
    while let Some(c) = chars.next() {
        if esc {
            match c {
                'n' => out.push('\n'),
                't' => out.push('\t'),
                'r' => out.push('\r'),
                'u' => {
                    let hex: String = chars.by_ref().take(4).collect();
                    out.push(char::from_u32(u32::from_str_radix(&hex, 16).ok()?)?);
                }
                c => out.push(c),
            }
            esc = false;
        } else if c == '\\' {
            esc = true;
        } else if c == '"' {
            return Some(out);
        } else {
            out.push(c);
        }
    }
    None
}
