#[test]
fn dialog_codes_parse_and_print_back() {
    for code in CODES {
        let ast = parse_format(code).unwrap_or_else(|e| panic!("{code}: {e}"));
        assert_eq!(print_format(&ast), code);
        let shown = format_value(&Value::Number(-1234.56789), &ast, &EN_US, None).text;
        assert!(!shown.is_empty(), "{code}");
    }
    let f = |code: &str, x: f64| {
        format_value(
            &Value::Number(x),
            &parse_format(code).unwrap(),
            &EN_US,
            None,
        )
        .text
    };
    // AOO's list previews (sample -1234.56789).
    assert_eq!(f("#,###.00", -1234.56789), "-1,234.57");
    assert_eq!(
        f("[$$-409]#,##0.00;[RED]-[$$-409]#,##0.00", -1234.56789),
        "-$1,234.57"
    );
    assert_eq!(
        f("#,##0.00 [$€-407];-#,##0.00 [$€-407]", 1234.5),
        "1,234.50 €"
    );
    assert_eq!(f("[$-407]DD.MM.YYYY", 36525.0), "31.12.1999");
    assert_eq!(
        f("[$SFr.-807] #,##0.00;[RED][$SFr.-807] -#,##0.00", -2.0),
        "SFr. -2.00"
    );
}
